const ELDER = 'Elder Rowan';

function say(id: string, name: string, ...pages: (string | DialoguePage)[]): Dialogue {
  return { id, name, pages: pages.map((p) => (typeof p === 'string' ? { text: p } : p)) };
}

function by(speaker: string, text: string): DialoguePage {
  return { speaker, text };
}

